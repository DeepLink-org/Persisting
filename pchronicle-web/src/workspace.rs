#[component]
fn AssistantPanel(
    run: Option<RunSummary>,
    analysis: Option<RunAnalysis>,
    turns: Vec<TurnSummary>,
    selected: Option<TurnDetail>,
    wide: bool,
    on_toggle_wide: EventHandler<MouseEvent>,
    on_close: EventHandler<MouseEvent>,
    on_turn: EventHandler<i64>,
    on_open_session: EventHandler<AssistantSessionMeta>,
) -> Element {
    let mut index = use_signal(|| load_index(&BrowserStore));
    let mut session_id = use_signal(|| None::<String>);
    let mut bound_query = use_signal(|| None::<String>);
    let mut thread = use_signal(empty_thread);
    let mut input = use_signal(String::new);
    let mut busy = use_signal(|| false);
    let mut settings = use_signal(|| false);
    let mut history_open = use_signal(|| false);
    let mut config = use_signal(llm::load_config);
    let mut step = use_signal(|| "Working…".to_string());
    let mut following = use_signal(|| true);
    let run_for_effect = run.clone();
    use_effect(move || {
        let Some(current) = run_for_effect.clone() else {
            return;
        };
        let query = current.query();
        if Some(query.clone()) == bound_query() {
            return;
        }
        bound_query.set(Some(query));
        let now = now_millis();
        let (next_index, id, next_thread) =
            restore_for_run(&BrowserStore, &current, &new_session_id(now), now);
        index.set(next_index);
        session_id.set(id);
        thread.set(next_thread);
    });
    let focused_turn_id = selected.as_ref().map(|detail| detail.summary.id);
    let update_step = Callback::new(move |next: String| step.set(next));
    let submit_run = run.clone();
    let submit_analysis = analysis.clone();
    let submit_copilot = Callback::new(move |()| {
        let question = input().trim().to_string();
        let Some(submit_run) = submit_run.clone() else {
            return;
        };
        let Some(submit_analysis) = submit_analysis.clone() else {
            return;
        };
        if question.is_empty() || busy() {
            return;
        }
        let config_value = config();
        if !config_value.is_configured() {
            const CONFIGURE_MESSAGE: &str =
                "Configure an OpenAI-compatible model in Settings before asking Assistant.";
            settings.set(true);
            let mut next_thread = thread();
            let already_shown = next_thread.messages.last().is_some_and(|message| {
                message.role == ThreadRole::Assistant && message.text == CONFIGURE_MESSAGE
            });
            if !already_shown {
                next_thread.messages.push(ThreadMessage {
                    role: ThreadRole::Assistant,
                    text: CONFIGURE_MESSAGE.into(),
                    tool_calls: None,
                    tool_call_id: None,
                    tool_name: None,
                    sql: None,
                    truncated: false,
                    reasoning_content: None,
                });
                thread.set(next_thread);
            }
            return;
        }

        let prior_thread = thread();
        let mut pending_thread = prior_thread.clone();
        pending_thread.messages.push(ThreadMessage {
            role: ThreadRole::User,
            text: question.clone(),
            tool_calls: None,
            tool_call_id: None,
            tool_name: None,
            sql: None,
            truncated: false,
            reasoning_content: None,
        });
        thread.set(pending_thread.clone());
        input.set(String::new());
        step.set("Working…".into());
        following.set(true);
        busy.set(true);
        spawn(async move {
            let report_step = |next: &str| update_step.call(next.to_string());
            let result = agent::answer(agent::AnswerRequest {
                config: &config_value,
                user_message: &question,
                run: &submit_run,
                analysis: &submit_analysis,
                focused_turn_id,
                thread: prior_thread,
                on_step: Some(&report_step),
            })
            .await;
            let finished = match result {
                Ok(answer) => answer.thread,
                Err(message) => {
                    pending_thread.messages.push(ThreadMessage {
                        role: ThreadRole::Assistant,
                        text: format!("Unable to complete analysis: {message}"),
                        tool_calls: None,
                        tool_call_id: None,
                        tool_name: None,
                        sql: None,
                        truncated: false,
                        reasoning_content: None,
                    });
                    pending_thread
                }
            };
            let now = now_millis();
            let id = session_id().unwrap_or_else(|| new_session_id(now));
            session_id.set(Some(id.clone()));
            let mut next_index = index();
            persist_indexed_thread(
                &BrowserStore,
                &mut next_index,
                &id,
                &submit_run,
                &finished,
                now,
            );
            index.set(next_index);
            thread.set(finished);
            busy.set(false);
        });
    });
    use_effect(move || {
        let _len = thread().messages.len();
        let _busy = busy();
        let _step = step();
        if following() {
            scroll_copilot_chat_to_bottom();
        }
    });
    let title = title_from_thread(&thread());
    let new_chat_enabled = can_start_new_chat(run.is_some(), &thread()) && !busy();
    let context_line = match (&run, &analysis, selected.as_ref()) {
        (None, _, _) => "Open a run to start a chat.".to_string(),
        (Some(_), None, _) => "Loading run details…".to_string(),
        (Some(_), Some(_), Some(detail)) => format!("Step {} in context", detail.summary.id),
        (Some(_), Some(_), None) => "Current run in context".to_string(),
    };
    let composer_enabled = run.is_some() && analysis.is_some() && !busy();
    let sessions = index().sessions;
    rsx! { aside { class: assistant_panel_class(wide),
        div { class: "pc2-copilot-head",
            div { class: "pc2-copilot-head-title", strong { "{title}" } span { "Read-only · selected run data" } }
            div { class: "pc2-copilot-actions",
                button {
                    aria_label: "New chat",
                    title: "New chat",
                    disabled: !new_chat_enabled,
                    onclick: move |_| {
                        if !new_chat_enabled { return; }
                        session_id.set(None);
                        thread.set(empty_thread());
                        history_open.set(false);
                    },
                    "+"
                }
                button {
                    aria_label: "Chat history",
                    title: "Chat history",
                    aria_pressed: history_open(),
                    disabled: busy(),
                    onclick: move |_| history_open.set(!history_open()),
                    "◷"
                }
                button { aria_label: "LLM settings", onclick: move |_| settings.set(true), "⚙" }
                AssistantWideToggle { wide, on_toggle: on_toggle_wide }
                button { aria_label: "Close Assistant", onclick: on_close, "×" }
            }
        }
        if history_open() {
            div { class: "pc2-copilot-history", role: "listbox", aria_label: "Assistant history",
                if sessions.is_empty() {
                    div { class: "pc2-copilot-history-empty", "No saved chats yet." }
                }
                for meta in sessions.iter().cloned() {
                    {
                        let active = session_id().as_deref() == Some(meta.id.as_str());
                        let row = meta.clone();
                        let delete_id = meta.id.clone();
                        rsx! {
                            div { class: if active { "pc2-copilot-history-row active" } else { "pc2-copilot-history-row" },
                                button {
                                    r#type: "button",
                                    class: "pc2-copilot-history-open",
                                    onclick: move |_| {
                                        if busy() { return; }
                                        let loaded = load_session_thread(&BrowserStore, &row.id);
                                        session_id.set(Some(row.id.clone()));
                                        thread.set(loaded);
                                        bound_query.set(Some(row.run.query()));
                                        history_open.set(false);
                                        following.set(true);
                                        on_open_session.call(row.clone());
                                    },
                                    strong { "{meta.title}" }
                                    span { "{short(&meta.run.session_id, 18)} · {relative_time(now_millis(), meta.updated_at)}" }
                                }
                                button {
                                    r#type: "button",
                                    class: "pc2-copilot-history-delete",
                                    aria_label: "Delete chat",
                                    onclick: move |event| {
                                        event.stop_propagation();
                                        let mut next = index();
                                        let fallback = delete_session(&mut next, &delete_id);
                                        let store = BrowserStore;
                                        store.remove(&session_storage_key(&delete_id));
                                        save_index(&BrowserStore, &next);
                                        index.set(next);
                                        if session_id().as_deref() == Some(delete_id.as_str()) {
                                            if let Some(id) = fallback {
                                                session_id.set(Some(id.clone()));
                                                thread.set(load_session_thread(&BrowserStore, &id));
                                            } else {
                                                session_id.set(None);
                                                thread.set(empty_thread());
                                            }
                                        }
                                    },
                                    "×"
                                }
                            }
                        }
                    }
                }
            }
        }
        div { class: "pc2-chat-wrap",
            div {
                id: ASSISTANT_CHAT_ID,
                class: "pc2-chat",
                onscroll: move |_| {
                    following.set(copilot_following_after_scroll(following(), copilot_chat_is_near_bottom()));
                },
                if thread().messages.is_empty() {
                    div { class: "pc2-chat-welcome", span { "◇" } strong { "Ask Assistant" }
                        if run.is_none() {
                            p { "Open a run, or select a previous chat from history." }
                        } else if config().is_configured() {
                            p { "Assistant can inspect this analysis, examine a step, or run read-only SQL." }
                        } else {
                            p { "Configure an OpenAI-compatible model in Settings before asking Assistant." }
                        }
                    }
                }
                for (index, message) in thread().messages.iter().enumerate() {
                    if !(message.role == ThreadRole::Assistant
                        && message.text.trim().is_empty()
                        && message.tool_calls.as_ref().is_some_and(|calls| !calls.is_empty()))
                    {
                        ChatBubble { key: "message-{index}", message: message.clone(), turns: turns.clone(), on_turn }
                    }
                }
                if busy() { div { class: "pc2-chat-working", span { class: "spinner" } "{step}" } }
            }
            if !thread().messages.is_empty() || busy() {
                if following() {
                    button {
                        class: "pc2-chat-follow",
                        r#type: "button",
                        aria_pressed: "true",
                        title: "Stop following new output",
                        aria_label: "Stop following new output",
                        onclick: move |_| following.set(false),
                        "Following"
                    }
                } else {
                    button {
                        class: "pc2-chat-follow jump",
                        r#type: "button",
                        title: "Jump to latest output and follow",
                        aria_label: "Jump to latest output and follow",
                        onclick: move |_| {
                            following.set(true);
                            scroll_copilot_chat_to_bottom();
                        },
                        "↓ Latest"
                    }
                }
            }
        }
        form { class: "pc2-composer pc2-composer-compact", onsubmit: move |event| { event.prevent_default(); submit_copilot.call(()); },
            textarea {
                value: "{input}",
                rows: "2",
                placeholder: if run.is_none() { "Open a run to start a chat…" } else if analysis.is_none() { "Loading run details…" } else { "Ask about this run…" },
                oninput: move |event| input.set(event.value()),
                onkeydown: move |event| if event.key() == Key::Enter && !event.modifiers().shift() { event.prevent_default(); submit_copilot.call(()); },
                disabled: !composer_enabled
            }
            button { class: "button primary", disabled: !composer_enabled || input().trim().is_empty(), "Send" }
        }
        div { class: "pc2-composer-context", "{context_line}" }
        if settings() { LlmSettings { config: config(), on_close: move |_| settings.set(false), on_save: move |value| { llm::save_config(&value); config.set(value); settings.set(false); } } }
    } }
}
#[component]
fn ChatBubble(
    message: ThreadMessage,
    turns: Vec<TurnSummary>,
    on_turn: EventHandler<i64>,
) -> Element {
    let message = if message.role == ThreadRole::Assistant {
        match agent::visible_assistant_text(&message.text) {
            None => return rsx! {},
            Some(text) => ThreadMessage { text, ..message },
        }
    } else {
        message
    };
    if message.role == ThreadRole::Tool {
        let action = message
            .tool_name
            .clone()
            .unwrap_or_else(|| "tool".to_string());
        return rsx! {
            div { class: "pc2-message tool",
                span { class: "pc2-action-label", "Running {action} ›" }
                if !message.text.trim().is_empty() {
                    details { summary { "Tool output" } pre { "{message.text}" } }
                }
            }
        };
    }
    let refs = turn_references(&message.text);
    let blocks = parse_rich_blocks(&message.text);
    rsx! { div { class: if message.role == ThreadRole::User { "pc2-message user" } else { "pc2-message assistant" },
        for (index, block) in blocks.into_iter().enumerate() {
            match block {
                RichBlock::Text(text) => rsx! { MessageText { key: "text-{index}", text } },
                RichBlock::Table(table) => rsx! { DataTable { key: "table-{index}", evidence: table.evidence, title: table.title, embedded: true } },
                RichBlock::Trajectory(trajectory) => {
                    let visible = turns.iter().filter(|turn| trajectory.turn_ids.contains(&turn.id)).cloned().collect::<Vec<_>>();
                    rsx! { div { key: "trajectory-{index}", class: "pc2-chat-component",
                        if let Some(title) = trajectory.title { strong { class: "pc2-chat-component-title", "{title}" } }
                        if visible.is_empty() { div { class: "pc2-data-empty", "Referenced steps are outside the loaded data window." } }
                        else { TrajectoryView { turns: visible, expanded_turn_id: None, detail: None, loading: false, embedded: true, view: "steps".to_string(), on_turn } }
                    } }
                },
            }
        }
        if let Some(sql) = &message.sql { details { class: "pc2-message-sql", summary { "Executed read-only SQL" } pre { "{sql}" } } }
        if message.truncated { div { class: "pc2-truncated", "The available data was limited or truncated; conclusions may be incomplete." } }
        if !refs.is_empty() { div { class: "pc2-citations", for id in refs { button { onclick: move |_| on_turn.call(id), "Step #{id}" } } } }
    } }
}

#[component]
fn MessageText(text: String) -> Element {
    rsx! { div { class: "pc2-message-text", for line in text.lines() { if let Some(item) = line.strip_prefix("- ") { div { class: "pc2-bullet", span { "•" } p { "{clean_markdown(item)}" } } } else if !line.trim().is_empty() { p { "{clean_markdown(line)}" } } } } }
}

fn short(value: &str, limit: usize) -> String {
    if value.chars().count() <= limit {
        value.into()
    } else {
        format!(
            "{}…",
            value
                .chars()
                .take(limit.saturating_sub(1))
                .collect::<String>()
        )
    }
}

fn format_ms(value: f64) -> String {
    if value >= 1000.0 {
        format!("{:.2}s", value / 1000.0)
    } else {
        format!("{value:.1}ms")
    }
}
fn optional_u64(value: Option<u64>) -> String {
    value
        .map(|value| value.to_string())
        .unwrap_or_else(|| "—".into())
}

#[derive(Clone, Debug, PartialEq)]
struct MixSegment {
    name: String,
    count: usize,
    share: f64,
}

#[derive(Clone, Debug, PartialEq)]
struct CoveragePoint {
    label: &'static str,
    observed: usize,
    total: usize,
}

fn compact_mix(items: &[DimensionAggregate], limit: usize) -> Vec<MixSegment> {
    let total: usize = items.iter().map(|item| item.turn_count).sum();
    if total == 0 || limit == 0 {
        return Vec::new();
    }
    let mut ranked = items.to_vec();
    ranked.sort_by(|left, right| right.turn_count.cmp(&left.turn_count));
    let mut segments: Vec<MixSegment> = ranked
        .iter()
        .take(limit)
        .map(|item| MixSegment {
            name: item.name.clone(),
            count: item.turn_count,
            share: percent(item.turn_count as f64, total as f64),
        })
        .collect();
    let rest: usize = ranked.iter().skip(limit).map(|item| item.turn_count).sum();
    if rest > 0 {
        segments.push(MixSegment {
            name: "other".into(),
            count: rest,
            share: percent(rest as f64, total as f64),
        });
    }
    if !segments.is_empty() {
        let used: f64 = segments
            .iter()
            .rev()
            .skip(1)
            .map(|segment| segment.share)
            .sum();
        if let Some(last) = segments.last_mut() {
            last.share = (100.0 - used).clamp(0.0, 100.0);
        }
    }
    segments
}

fn coverage_points(
    latency_observed: usize,
    latency_total: usize,
    ttft_observed: usize,
    ttft_total: usize,
    timestamp_observed: usize,
    timestamp_total: usize,
    token_observed: usize,
    token_total: usize,
) -> Vec<CoveragePoint> {
    vec![
        CoveragePoint {
            label: "Latency",
            observed: latency_observed,
            total: latency_total,
        },
        CoveragePoint {
            label: "TTFT",
            observed: ttft_observed,
            total: ttft_total,
        },
        CoveragePoint {
            label: "Timestamp",
            observed: timestamp_observed,
            total: timestamp_total,
        },
        CoveragePoint {
            label: "Tokens",
            observed: token_observed,
            total: token_total,
        },
    ]
}

fn mix_title(segments: &[MixSegment]) -> String {
    segments
        .iter()
        .map(|segment| format!("{} {}", segment.name, segment.count))
        .collect::<Vec<_>>()
        .join(" · ")
}

fn percent(value: f64, total: f64) -> f64 {
    if !value.is_finite() || !total.is_finite() || total <= 0.0 {
        0.0
    } else {
        (value / total * 100.0).clamp(0.0, 100.0)
    }
}
fn sampled_turns(turns: &[TurnSummary], limit: usize) -> Vec<TurnSummary> {
    if turns.len() <= limit || limit < 2 {
        return turns.to_vec();
    }
    (0..limit)
        .map(|index| index * (turns.len() - 1) / (limit - 1))
        .map(|index| turns[index].clone())
        .collect()
}
fn turn_metric(turn: &TurnSummary, metric: &str) -> Option<f64> {
    match metric {
        "tokens" => turn.total_tokens.map(|value| value as f64),
        _ => turn.latency_ms,
    }
}
fn metric_value(turn: &TurnSummary, metric: &str) -> String {
    match metric {
        "tokens" => turn
            .total_tokens
            .map(|value| format!("{value} tokens"))
            .unwrap_or_else(|| "no token sample".into()),
        _ => turn
            .latency_ms
            .map(format_ms)
            .unwrap_or_else(|| "no latency sample".into()),
    }
}
fn clean_markdown(value: &str) -> String {
    value.replace("**", "").replace('`', "")
}
fn turn_references(value: &str) -> Vec<i64> {
    let mut ids = Vec::new();
    let mut rest = value;
    while let Some((_, next)) = rest.split_once("[turn:") {
        if let Some((raw, after)) = next.split_once(']') {
            if let Ok(id) = raw.parse() {
                if !ids.contains(&id) {
                    ids.push(id);
                }
            }
            rest = after;
        } else {
            break;
        }
    }
    ids
}

fn url_param(name: &str) -> Option<String> {
    let search = web_sys::window()?.location().search().ok()?;
    web_sys::UrlSearchParams::new_with_str(&search)
        .ok()?
        .get(name)
}

fn analyze_workspace_url(session_id: &str) -> String {
    if session_id.is_empty() {
        "/?page=tools".into()
    } else {
        format!(
            "/?page=tools&analysis_session={}",
            urlencoding::encode(session_id)
        )
    }
}

fn analysis_url_sync_target(session_id: &str, seed_scope_pending: bool) -> Option<String> {
    if seed_scope_pending && session_id.is_empty() {
        None
    } else {
        Some(analyze_workspace_url(session_id))
    }
}

fn run_analysis_scope(
    catalog: &QueryCatalog,
    run: RunSummary,
) -> crate::analysis_session::AnalysisScope {
    crate::analysis_session::AnalysisScope::from_run(catalog, run)
}

#[allow(clippy::too_many_arguments)]
fn sync_workspace_url(
    page: &str,
    analysis_session_id: &str,
    analysis_seed_scope_pending: bool,
    run: Option<&RunSummary>,
    query: &str,
    dataset_filter: &str,
    status: &str,
    sort: &str,
    direction: &str,
    path: &str,
    file_prefix: &str,
    workspace: &str,
    view: &str,
    source: &str,
    turn_query: &str,
    turn_id: Option<i64>,
) {
    let Some(window) = web_sys::window() else {
        return;
    };
    if page == "tools" {
        let Some(url) = analysis_url_sync_target(analysis_session_id, analysis_seed_scope_pending)
        else {
            return;
        };
        let _ = window
            .history()
            .and_then(|history| history.replace_state_with_url(&JsValue::NULL, "", Some(&url)));
        return;
    }
    if page == "physical" {
        return;
    }
    let mut params = vec![format!("page={}", urlencoding::encode(page))];
    if let Some(run) = run.filter(|_| page == "detail") {
        params.push(format!("dataset={}", urlencoding::encode(&run.dataset)));
        params.push(format!("file={}", urlencoding::encode(&run.file)));
        if let Some(run_id) = run.run_id.as_deref().filter(|value| !value.is_empty()) {
            params.push(format!("run_id={}", urlencoding::encode(run_id)));
        }
        params.push(format!("agent_id={}", urlencoding::encode(&run.agent_id)));
        params.push(format!(
            "session_id={}",
            urlencoding::encode(&run.session_id)
        ));
        if let Some(root) = &run.root_session_id {
            params.push(format!("root_session_id={}", urlencoding::encode(root)));
        }
        params.push(format!("workspace={}", urlencoding::encode(workspace)));
        params.push(format!("view={}", urlencoding::encode(view)));
        params.push(format!("source={}", urlencoding::encode(source)));
        if !turn_query.is_empty() {
            params.push(format!("turn_q={}", urlencoding::encode(turn_query)));
        }
        if let Some(turn_id) = turn_id {
            params.push(format!("turn={turn_id}"));
        }
    } else if page == "runs" {
        if !query.is_empty() {
            params.push(format!("q={}", urlencoding::encode(query)));
        }
        params.push(format!("status={}", urlencoding::encode(status)));
        if dataset_filter != "all" {
            params.push(format!(
                "dataset_filter={}",
                urlencoding::encode(dataset_filter)
            ));
        }
        params.push(format!("sort={}", urlencoding::encode(sort)));
        params.push(format!("direction={}", urlencoding::encode(direction)));
        if !path.is_empty() {
            params.push(format!("path={}", urlencoding::encode(path)));
        }
        if !file_prefix.is_empty() {
            params.push(format!("file_prefix={}", urlencoding::encode(file_prefix)));
        }
    }
    let url = format!("/?{}", params.join("&"));
    let _ = window
        .history()
        .and_then(|history| history.replace_state_with_url(&JsValue::NULL, "", Some(&url)));
}

