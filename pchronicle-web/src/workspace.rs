#[derive(Clone, Debug, PartialEq)]
struct WorkspaceNotice {
    title: String,
    summary: String,
    detail: String,
    turn_id: Option<i64>,
}

fn workspace_notice(detail: String) -> WorkspaceNotice {
    WorkspaceNotice {
        title: "Workspace request failed".into(),
        summary: detail
            .lines()
            .next()
            .unwrap_or("Request failed")
            .to_string(),
        detail,
        turn_id: None,
    }
}

fn evidence_notice(turn_id: i64, detail: &str) -> WorkspaceNotice {
    WorkspaceNotice {
        title: "Step details could not be decoded".into(),
        summary: format!("Step #{turn_id} · {}", type_mismatch_summary(detail)),
        detail: detail.to_string(),
        turn_id: Some(turn_id),
    }
}

fn type_mismatch_summary(detail: &str) -> String {
    let received = detail
        .split("invalid type: ")
        .nth(1)
        .and_then(|rest| rest.split([',', ' ']).next())
        .filter(|value| !value.is_empty());
    let expected = detail
        .split("expected a ")
        .nth(1)
        .and_then(|rest| rest.split_whitespace().next())
        .map(|value| value.trim_end_matches(['.', ',']));
    match (expected, received) {
        (Some(expected), Some(received)) => format!("Expected {expected}, received {received}"),
        _ => "The step data did not match the expected format".into(),
    }
}

